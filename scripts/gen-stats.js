#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';
import { collectStats } from './collect-stats.js';

const root = resolve(new URL('..', import.meta.url).pathname);
const stats = collectStats();
const bundlePath = resolve(root, 'index.html');
const generatedStatsPath = resolve(root, 'src/data/generatedStats.js');

if (existsSync(bundlePath)) {
  const html = readFileSync(bundlePath, 'utf8');
  stats.bundleBytes = Buffer.byteLength(html, 'utf8');
  stats.bundleKB = Math.round(stats.bundleBytes / 1024);
  stats.bundleLines = html.split('\n').length;
}

const previousStats = readPreviousGeneratedStats(generatedStatsPath);
if (process.env.DIOGNOSIS_STATS_GENERATED_AT) {
  stats.generatedAt = new Date(process.env.DIOGNOSIS_STATS_GENERATED_AT).toISOString();
} else if (previousStats && statsEquivalent(stats, previousStats)) {
  stats.generatedAt = previousStats.generatedAt;
}

const generatedSource = `// Auto-generated by scripts/gen-stats.js. Do not edit by hand.
const DIOGNOSIS_STATS = ${JSON.stringify(stats, null, 2)};
`;
writeFileSync(generatedStatsPath, generatedSource, 'utf8');

function readPreviousGeneratedStats(filePath) {
  if (!existsSync(filePath)) return null;
  const source = readFileSync(filePath, 'utf8');
  const match = source.match(/const DIOGNOSIS_STATS = (\{[\s\S]*?\n\});/);
  if (!match) return null;
  try {
    return JSON.parse(match[1]);
  } catch {
    return null;
  }
}

function statsEquivalent(a, b) {
  const normalize = (value) => {
    const copy = { ...value };
    delete copy.generatedAt;
    return JSON.stringify(copy);
  };
  return normalize(a) === normalize(b);
}

function generatedDate(stats) {
  return new Date(stats.generatedAt).toISOString().slice(0, 10);
}

function replaceMarkedBlock(content, start, end, replacement, fileLabel) {
  if (!content.includes(start) || !content.includes(end)) {
    throw new Error(`${fileLabel} is missing generated block markers ${start} / ${end}`);
  }
  return content.replace(new RegExp(`${start}[\\s\\S]*?${end}`), replacement);
}

const readmePath = resolve(root, 'README.md');
const readme = readFileSync(readmePath, 'utf8');
const start = '<!-- DIOGNOSIS_STATS_START -->';
const end = '<!-- DIOGNOSIS_STATS_END -->';
const statsBlock = `${start}
- **${stats.drugs} drugs** in DRUG_DB
- **${stats.studies} evidence entries** in STUDY_DB (${stats.authoritySourceStudies} authority-source; ${stats.primaryLiteratureStudies} primary-literature; ${stats.modeledContextStudies} modeled context)
- **${stats.ddiPairs} interaction pairs** (${stats.severeDdi} severe, ${stats.moderateDdi} moderate, ${stats.mildDdi} mild)
- **${stats.metaboliteEntries} metabolite entries** across **${stats.metaboliteParents} parent substances** (${stats.metaboliteActors} first-class metabolite actors)
- **${stats.pkParams} absolute PK simulation profiles** with relative fallback for half-life-only drugs
- **${stats.genotypeGenes} genotype genes** and **${stats.receptorScores} receptor score profiles**
- **${stats.externalSubstanceMappings} RxNorm identity mappings**, **${stats.pgxMarkerRows} PGx marker rows**, and **${stats.pgxActionSummaries} PGx action summaries** (${stats.authorityLinkedPgxActions} linked to an FDA authority table)
- **${stats.beersFlags} Beers flags** and **${stats.washoutRules} washout rules**
- **${stats.bundleKB || 'Not yet built'} KB** generated bundle${stats.bundleLines ? ` (${stats.bundleLines} lines)` : ''}
${end}`;

let nextReadme;
if (readme.includes(start) && readme.includes(end)) {
  nextReadme = readme.replace(new RegExp(`${start}[\\s\\S]*?${end}`), statsBlock);
} else {
  nextReadme = readme.replace(
    '---\n\n## Features',
    `---\n\n## Live Source Stats\n\n${statsBlock}\n\n---\n\n## Features`
  );
}
writeFileSync(readmePath, nextReadme, 'utf8');

const publicTrustPath = resolve(root, 'docs/PUBLIC_TRUST.md');
if (existsSync(publicTrustPath)) {
  const trustStart = '<!-- PUBLIC_TRUST_STATS_START -->';
  const trustEnd = '<!-- PUBLIC_TRUST_STATS_END -->';
const trustBlock = `${trustStart}
- **${stats.authoritySourceStudies} \`STUDY_DB\` entries** link to regulatory authorities or recognized guideline publishers.
- **${stats.primaryLiteratureStudies} entries** link to claim-specific primary literature; **${stats.modeledContextStudies} entries** are explicitly modeled context and cannot preserve severe output.
- **${stats.studiesWithPmid} entries** include PMIDs. Authority and literature linkage describe provenance, not independent Diognosis clinical validation.
${trustEnd}`;
  let trust = readFileSync(publicTrustPath, 'utf8')
    .replace(/^Generated: .*/m, `Generated: ${generatedDate(stats)}`);
  trust = replaceMarkedBlock(trust, trustStart, trustEnd, trustBlock, 'docs/PUBLIC_TRUST.md');
  writeFileSync(publicTrustPath, trust, 'utf8');
}

const launchTrustPath = resolve(root, 'docs/LAUNCH_DATA_TRUST_AUDIT.md');
if (existsSync(launchTrustPath)) {
  const launchStart = '<!-- LAUNCH_DATA_TRUST_STATS_START -->';
  const launchEnd = '<!-- LAUNCH_DATA_TRUST_STATS_END -->';
  const launchBlock = `${launchStart}
| Metric | Count |
| --- | ---: |
| Drugs in \`DRUG_DB\` | ${stats.drugs} |
| Evidence entries in \`STUDY_DB\` | ${stats.studies} |
| Authority-source evidence entries | ${stats.authoritySourceStudies} |
| Primary-literature evidence entries | ${stats.primaryLiteratureStudies} |
| Modeled-context entries (not severity-bearing) | ${stats.modeledContextStudies} |
| Evidence entries with PMIDs | ${stats.studiesWithPmid} |
| RxNorm identity mappings | ${stats.externalSubstanceMappings} |
| PGx marker rows | ${stats.pgxMarkerRows} |
| PGx action summaries | ${stats.pgxActionSummaries} |
| PGx actions linked to FDA authority table | ${stats.authorityLinkedPgxActions} |
| Interaction pairs | ${stats.ddiPairs} |
| Severe interaction pairs | ${stats.severeDdi} |
| Moderate interaction pairs | ${stats.moderateDdi} |
| Mild interaction pairs | ${stats.mildDdi} |
${launchEnd}`;
  let launchTrust = readFileSync(launchTrustPath, 'utf8')
    .replace(/^Audit date: .*/m, `Audit date: ${generatedDate(stats)}`);
  launchTrust = replaceMarkedBlock(launchTrust, launchStart, launchEnd, launchBlock, 'docs/LAUNCH_DATA_TRUST_AUDIT.md');
  writeFileSync(launchTrustPath, launchTrust, 'utf8');
}

process.stdout.write(`Generated stats: ${stats.drugs} drugs, ${stats.studies} studies, ${stats.ddiPairs} DDI pairs\n`);
