#!/usr/bin/env node
import { resolve } from 'path';
import { ROOT } from './lib/medcheck-source-loader.js';
import { readJson, writeText } from './lib/enrichment-common.js';

const OUT = resolve(ROOT, 'src/data/generatedEnrichmentReviewData.js');
const queue = readJson(resolve(ROOT, 'data/enrichment/review-queue/enrichment-review-queue-v2.json'), { items: [] });
const grouped = readJson(resolve(ROOT, 'data/enrichment/review-queue/grouped-review-candidates-v2.json'), { candidates: [] });
const dashboard = readJson(resolve(ROOT, 'docs/audits/knowledge-growth-dashboard.json'), {});
const campaign = readJson(resolve(ROOT, 'docs/audits/three-x-enrichment-report.json'), {});

const topRows = (queue.items || [])
  .filter(item => item.lane !== 'existing_enrichment_queue')
  .slice(0, 120)
  .map(item => ({
    id: item.id,
    lane: item.lane,
    priority: item.priority,
    layer: item.layer,
    store: item.store,
    suggestedTarget: item.suggestedTarget,
    reason: item.reason,
    affectedDrugs: item.affectedDrugs || [],
    affectedGenes: item.affectedGenes || [],
    affectedMetabolites: item.affectedMetabolites || [],
    sourceTruthStatuses: item.sourceTruthStatuses || [],
    evidenceIdentifiers: (item.evidenceIdentifiers || []).slice(0, 8),
    reviewStatus: item.reviewStatus || 'pending_professional_review',
  }));

const data = {
  schema: 'diognosis.generated-enrichment-review-data.v1',
  generatedAt: new Date().toISOString(),
  summary: {
    queueV2Items: queue.totalItems || 0,
    preservedV1Items: queue.preservedV1Items || 0,
    candidateRelationItems: queue.candidateRelationItems || 0,
    groupedV2Candidates: grouped.totalCandidates || 0,
    candidateRows: dashboard.candidates?.totalCandidates || 0,
    stagedRecords: dashboard.staged?.totalRecords || 0,
    p1QueueItems: queue.priorityCounts?.P1 || 0,
    corePromotions: campaign.promotions?.corePromotions || 0,
  },
  rows: topRows,
};

writeText(OUT, `// Generated by scripts/enrich/generate-enrichment-review-data.js
// Review-layer data only. It must not affect scoring or public severity.
const GENERATED_ENRICHMENT_REVIEW_DATA = ${JSON.stringify(data, null, 2)};
`);
console.log(JSON.stringify({ ok: true, rows: data.rows.length, out: OUT }, null, 2));
